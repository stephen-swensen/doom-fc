#!/usr/bin/env python3
"""Generate doom-fc's data-table modules from the linuxdoom-1.10 C source.

    python3 tools/gen_tables.py ../DOOM/linuxdoom-1.10 src

Writes src/tables.fc, src/info.fc, src/sounds.fc and src/dstrings.fc. These
are straight transcriptions of id's tables (GPLv2, like the rest of this
port) — regenerate rather than hand-edit.
"""
import re
import sys
import os

RESERVED = set("""let mut const struct union enum error module namespace import from as
extern private match with when if then else for in do loop break continue return defer
ignore some true false none ok err void guarded unguarded checked unchecked alloc alloca
free sizeof alignof bitcast enum_of default assert static_assert error_name
atomic_load_acquire atomic_store_release i8 i16 i32 i64 u8 u16 u32 u64 isize usize f32 f64
bool char any str cstr""".split())


def ident(name):
    n = name.lower()
    if n in RESERVED:
        n = n + "_x"
    if n[0].isdigit():
        n = "n" + n
    return n


def strip_comments(t):
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    return re.sub(r'//[^\n]*', '', t)


def read(path):
    return open(path, encoding='latin1').read()


HEADER = "// GENERATED by tools/gen_tables.py from id Software's linuxdoom-1.10\n" \
         "// source (GPLv2). Do not hand-edit; regenerate instead.\n\n"


def c_array(text, name):
    m = re.search(name + r'\s*\[[^\]]*\]\s*=\s*\{(.*?)\};', text, flags=re.S)
    return [v.strip() for v in m.group(1).split(',') if v.strip()]


def wrap(vals, per=10, indent="        "):
    lines = []
    for i in range(0, len(vals), per):
        lines.append(indent + ", ".join(vals[i:i + per]))
    return ",\n".join(lines)


def gen_tables(src, out):
    t = strip_comments(read(os.path.join(src, 'tables.c')))
    ft = c_array(t, 'finetangent')
    fs = c_array(t, 'finesine')
    ta = c_array(t, 'tantoangle')
    with open(os.path.join(out, 'tables.fc'), 'w') as f:
        f.write(HEADER)
        f.write("// Trig lookup tables (tables.c). finecosine is finesine offset by a\n"
                "// quarter turn; use tables.finecos(i).\n\n")
        f.write("module tables =\n")
        f.write("    let fineangles = 8192\n")
        f.write("    let finemask = fineangles - 1\n")
        f.write("    let angletofineshift = 19\n")
        f.write("    let slope_range = 2048\n")
        f.write("    let slopebits = 11\n")
        f.write("    let dbits = 5\n\n")
        f.write("    // finetangent[4096] immediately followed by finesine[10240], as the\n"
                "    // two arrays sit in memory in the original: the renderer can index\n"
                "    // finesine slightly below 0 (R_ScaleFromGlobalAngle at extreme\n"
                "    // angles) and must then read the tail of finetangent, as DOOM does.\n")
        f.write("    let fine = i32[] {\n" + wrap(ft + fs) + "\n    }\n\n")
        f.write("    let tan = (i: i32) -> fine[i]\n")
        f.write("    let sin = (i: i32) -> fine[4096 + i]\n")
        f.write("    let cos = (i: i32) -> fine[4096 + fineangles / 4 + i]\n\n")
        f.write("    let tantoangle = u32[] {\n" + wrap([v + "u32" for v in ta], 8) + "\n    }\n\n")
        f.write("    // SlopeDiv\n")
        f.write("    let slope_div = (num: u32, den: u32) ->\n")
        f.write("        if den < 512u32 then slope_range\n")
        f.write("        else\n")
        f.write("            let ans = (num << 3) / (den >> 8)\n")
        f.write("            if ans <= (u32) slope_range then (i32) ans else slope_range\n")


def enum_body(text, last):
    m = re.search(r'typedef\s+enum\s*\{([^{}]*)\}\s*' + last + r'\s*;', text, flags=re.S)
    names = []
    for v in m.group(1).split(','):
        v = v.strip()
        if not v:
            continue
        v = v.split('=')[0].strip()
        names.append(v)
    return names


def gen_info(src, out):
    h = strip_comments(read(os.path.join(src, 'info.h')))
    c = strip_comments(read(os.path.join(src, 'info.c')))
    sprites = enum_body(h, 'spritenum_t')
    states = enum_body(h, 'statenum_t')
    mobjtypes = enum_body(h, 'mobjtype_t')
    sfxh = strip_comments(read(os.path.join(src, 'sounds.h')))
    sfxnames = enum_body(sfxh, 'sfxenum_t')

    # sprnames
    m = re.search(r'sprnames\s*\[[^\]]*\]\s*=\s*\{(.*?)\};', c, flags=re.S)
    sprnames = re.findall(r'"(\w+)"', m.group(1))

    # states
    m = re.search(r'state_t\s+states\s*\[[^\]]*\]\s*=\s*\{(.*)\};\s*mobjinfo_t', c, flags=re.S)
    rows = re.findall(r'\{\s*(SPR_\w+)\s*,\s*([^,]+?)\s*,\s*(-?\d+)\s*,\s*\{\s*(\w+)\s*\}\s*,\s*(S_\w+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*\}', m.group(1))
    assert len(rows) == len(states) - 1, (len(rows), len(states))

    actions = []
    for r in rows:
        if r[3] != 'NULL' and r[3] not in actions:
            actions.append(r[3])

    def expr(v):
        v = v.strip()
        v = re.sub(r'\bFRACUNIT\b', 'fx.fracunit', v)
        v = re.sub(r'\bMF_(\w+)', lambda mm: 'mf.' + ident(mm.group(1)), v)
        v = re.sub(r'\bS_(\w+)', lambda mm: 'sn.' + ident(mm.group(1)), v)
        v = re.sub(r'\bsfx_(\w+)', lambda mm: 'sfx.' + ident(mm.group(1)), v)
        v = re.sub(r'\bMT_(\w+)', lambda mm: 'mt.' + ident(mm.group(1)), v)
        return v

    # mobjinfo
    m = re.search(r'mobjinfo_t\s+mobjinfo\s*\[[^\]]*\]\s*=\s*\{(.*)\};', c, flags=re.S)
    infos = re.findall(r'\{([^{}]*)\}', m.group(1))
    assert len(infos) == len(mobjtypes) - 1, (len(infos), len(mobjtypes))
    fields = ['doomednum', 'spawnstate', 'spawnhealth', 'seestate', 'seesound', 'reactiontime',
              'attacksound', 'painstate', 'painchance', 'painsound', 'meleestate', 'missilestate',
              'deathstate', 'xdeathstate', 'deathsound', 'speed', 'radius', 'height', 'mass',
              'damage', 'activesound', 'flags', 'raisestate']

    with open(os.path.join(out, 'info.fc'), 'w') as f:
        f.write(HEADER)
        f.write("// Thing / state / sprite tables (info.h, info.c).\n\n")
        f.write("// Codepointer for a state. NULL in the C tables is `nil`.\n")
        f.write("enum actionf =\n    | nil\n")
        for a in actions:
            f.write("    | " + ident(a) + "\n")
        f.write("\n")
        f.write("struct state =\n    sprite: i32\n    frame: i32\n    tics: i32\n"
                "    action: actionf\n    nextstate: i32\n    misc1: i32\n    misc2: i32\n\n")
        f.write("struct mobjinfo =\n")
        for fl in fields:
            f.write("    " + fl + ": i32\n")
        f.write("\n")

        f.write("// spritenum_t\nmodule spr =\n")
        for i, s in enumerate(sprites):
            if s == 'NUMSPRITES':
                f.write("    let numsprites = %d\n" % i)
            else:
                f.write("    let %s = %d\n" % (ident(s[4:]), i))
        f.write("\n// statenum_t\nmodule sn =\n")
        for i, s in enumerate(states):
            if s == 'NUMSTATES':
                f.write("    let numstates = %d\n" % i)
            else:
                f.write("    let %s = %d\n" % (ident(s[2:]), i))
        f.write("\n// mobjtype_t\nmodule mt =\n")
        for i, s in enumerate(mobjtypes):
            if s == 'NUMMOBJTYPES':
                f.write("    let nummobjtypes = %d\n" % i)
            else:
                f.write("    let %s = %d\n" % (ident(s[3:]), i))
        f.write("\nmodule info =\n")
        f.write("    let sprnames = (const str)[] {\n" +
                wrap(['"%s"' % s for s in sprnames], 12) + "\n    }\n\n")
        f.write("    let mut states = state[] {\n")
        out_rows = []
        for i, r in enumerate(rows):
            act = 'actionf.' + (ident(r[3]) if r[3] != 'NULL' else 'nil')
            out_rows.append("        state { sprite = spr.%s, frame = %s, tics = %s, action = %s, "
                            "nextstate = sn.%s, misc1 = %s, misc2 = %s }" %
                            (ident(r[0][4:]), expr(r[1]), r[2], act, ident(r[4][2:]), r[5], r[6]))
        f.write(",\n".join(out_rows) + "\n    }\n\n")
        f.write("    let mut mobjinfo = mobjinfo[] {\n")
        out_rows = []
        for i, body in enumerate(infos):
            vals = [v.strip() for v in body.split(',') if v.strip()]
            assert len(vals) == len(fields), (i, vals)
            out_rows.append("        mobjinfo {\n" + ",\n".join(
                "            %s = %s" % (fl, expr(v)) for fl, v in zip(fields, vals)) + "\n        }")
        f.write(",\n".join(out_rows) + "\n    }\n")


def gen_sounds(src, out):
    h = strip_comments(read(os.path.join(src, 'sounds.h')))
    c = strip_comments(read(os.path.join(src, 'sounds.c')))
    sfxnames = enum_body(h, 'sfxenum_t')
    musnames = enum_body(h, 'musicenum_t')
    m = re.search(r'S_music\s*\[\s*\]\s*=\s*\{(.*?)\};', c, flags=re.S)
    music = re.findall(r'\{\s*(?:"(\w+)"\s*,\s*0|0)\s*\}', m.group(1))
    m = re.search(r'S_sfx\s*\[\s*\]\s*=\s*\{(.*?)\};', c, flags=re.S)
    sfx = re.findall(r'\{\s*"(\w+)"\s*,\s*(\w+)\s*,\s*(-?\d+)\s*,\s*([^,]+?)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*\}', m.group(1))
    # one row per sfxenum_t value (sfxnames ends with NUMSFX)
    assert len(sfx) == len(sfxnames) - 1 and sfx[0][0] == 'none', (len(sfx), len(sfxnames))
    with open(os.path.join(out, 'sounds.fc'), 'w') as f:
        f.write(HEADER)
        f.write("// Sound and music tables (sounds.h, sounds.c).\n\n")
        f.write("struct sfxinfo =\n    name: const str\n    singularity: bool\n    priority: i32\n"
                "    link: i32          // index into sounds.s_sfx, -1 = none\n"
                "    pitch: i32\n    volume: i32\n    data: u8[]\n    usefulness: i32\n    lumpnum: i32\n\n")
        f.write("struct musicinfo =\n    name: const str\n    lumpnum: i32\n    data: u8[]\n    handle: i32\n\n")
        f.write("// sfxenum_t\nmodule sfx =\n")
        for i, s in enumerate(sfxnames):
            if s == 'NUMSFX':
                f.write("    let numsfx = %d\n" % i)
            else:
                f.write("    let %s = %d\n" % (ident(s[4:]), i))
        f.write("\n// musicenum_t\nmodule mus =\n")
        for i, s in enumerate(musnames):
            if s == 'NUMMUSIC':
                f.write("    let nummusic = %d\n" % i)
            else:
                f.write("    let %s = %d\n" % (ident(s[4:]), i))
        f.write("\nmodule sounds =\n")
        f.write("    let mut s_music = musicinfo[] {\n")
        rows = []
        for name in music:
            rows.append('        musicinfo { name = "%s", lumpnum = 0, handle = 0 }' % name)
        f.write(",\n".join(rows) + "\n    }\n\n")
        f.write("    let mut s_sfx = sfxinfo[] {\n")
        # S_sfx[0] is the C table's own "none" dummy, matched like any row
        rows = []
        for s in sfx:
            link = s[3]
            if link == '0':
                link = '-1'
            else:
                link = 'sfx.' + ident(re.search(r'sfx_(\w+)', link).group(1))
            rows.append('        sfxinfo { name = "%s", singularity = %s, priority = %s, link = %s, pitch = %s, volume = %s, usefulness = 0, lumpnum = 0 }'
                        % (s[0], 'true' if s[1] == 'true' else 'false', s[2], link, s[4], s[5]))
        f.write(",\n".join(rows) + "\n    }\n")


def gen_strings(src, out):
    t = read(os.path.join(src, 'd_englsh.h'))
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    t = re.sub(r'\\\s*\n', ' ', t)
    defs = {}
    order = []
    for m in re.finditer(r'^#define\s+(\w+)\s+(.*?)$', t, flags=re.M):
        name, body = m.group(1), m.group(2).strip()
        body = re.sub(r'//.*$', '', body).strip()
        if not body or name.startswith('__'):
            continue
        defs[name] = body
        order.append(name)

    def value(name, depth=0):
        body = defs[name]
        out_s = ''
        pos = 0
        toks = re.findall(r'"(?:[^"\\]|\\.)*"|\w+', body)
        if not toks:
            return None
        for tok in toks:
            if tok.startswith('"'):
                out_s += bytes(tok[1:-1], 'latin1').decode('unicode_escape')
            elif tok in defs:
                v = value(tok, depth + 1)
                if v is None:
                    return None
                out_s += v
            else:
                return None
        return out_s

    def fc_lit(s):
        r = ''
        for ch in s:
            o = ord(ch)
            if ch == '\n':
                r += '\\n'
            elif ch == '"':
                r += '\\"'
            elif ch == '\\':
                r += '\\\\'
            elif ch == '%':
                r += '%%'
            elif o < 32 or o > 126:
                r += '\\x%02x' % o
            else:
                r += ch
        return '"' + r + '"'

    with open(os.path.join(out, 'dstrings.fc'), 'w') as f:
        f.write(HEADER)
        f.write("// English UI strings (d_englsh.h). `%%s` in a string is a printf slot\n"
                "// the menu code fills in by hand.\n\n")
        f.write("module dstr =\n")
        for name in order:
            v = value(name)
            if v is None:
                continue
            f.write("    let %s = %s\n" % (ident(name), fc_lit(v)))


def gen_gamma(src, out):
    t = strip_comments(read(os.path.join(src, 'v_video.c')))
    m = re.search(r'gammatable\s*\[5\]\s*\[256\]\s*=\s*\{(.*?)\};', t, flags=re.S)
    vals = re.findall(r'\d+', m.group(1))
    assert len(vals) == 5 * 256, len(vals)
    with open(os.path.join(out, 'gamma.fc'), 'w') as f:
        f.write(HEADER)
        f.write("// Gamma correction ramps (v_video.c gammatable[5][256], flattened).\n\n")
        f.write("module gammatbl =\n")
        f.write("    let table = u8[] {\n" + wrap([v + "u8" for v in vals], 16) + "\n    }\n")


def gen_random(src, out):
    t = strip_comments(read(os.path.join(src, 'm_random.c')))
    vals = c_array(t, 'rndtable')
    assert len(vals) == 256, len(vals)
    with open(os.path.join(out, 'random.fc'), 'w') as f:
        f.write(HEADER)
        f.write("// m_random: the 256-entry table every \"random\" number comes from.\n"
                "// P_Random drives the playsim (and so demo sync); M_Random is for\n"
                "// everything that must not disturb it.\n\n")
        f.write("module rnd =\n")
        f.write("    let rndtable = u8[] {\n" + wrap([v + "u8" for v in vals], 16) + "\n    }\n\n")
        f.write("    let mut rndindex = 0\n")
        f.write("    let mut prndindex = 0\n\n")
        f.write("    // P_Random: playsim random, synced across net games and demos\n")
        f.write("    let p_random = () ->\n")
        f.write("        prndindex = (prndindex + 1) & 0xff\n")
        f.write("        (i32) rndtable[prndindex]\n\n")
        f.write("    // M_Random: everything else\n")
        f.write("    let m_random = () ->\n")
        f.write("        rndindex = (rndindex + 1) & 0xff\n")
        f.write("        (i32) rndtable[rndindex]\n\n")
        f.write("    let clear_random = () ->\n")
        f.write("        rndindex = 0\n")
        f.write("        prndindex = 0\n")


if __name__ == '__main__':
    src, out = sys.argv[1], sys.argv[2]
    gen_tables(src, out)
    gen_info(src, out)
    gen_sounds(src, out)
    gen_strings(src, out)
    gen_gamma(src, out)
    gen_random(src, out)
    print("ok")
